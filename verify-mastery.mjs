import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {clientHarness} from './verify-blocked.mjs';
const context=vm.createContext({});vm.runInContext(fs.readFileSync('public/play/mastery.js','utf8'),context);
const {PotionMastery:M}=context,values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
let profile=M.create(storage);
assert.equal(profile.status().rank.name,'Squire');
const clear={level:1,medal:3,combo:5};
const first=profile.award(clear);assert(first.promoted);assert.equal(first.after.rank.name,'Apprentice');
assert.equal(profile.award(clear).earned,0,'Replaying the same brew must not farm mastery');
assert.equal(profile.award({...clear,combo:8}).earned,45,'Only the improvement is awarded');
profile=M.create(storage);assert.equal(profile.status().xp,first.earned+45,'Mastery survives reload');
for(let i=1;i<=45;i++)profile.award({...clear,daily:true,day:`2026-09-${String(1+(i%28)).padStart(2,'0')}`});
assert(profile.status().xp>6000);assert.equal(profile.status().rank.name,'Apprentice','Easy daily clears cannot bypass skill gates');
profile.award({...clear,level:25,rescued:true});assert.equal(profile.status().level,1,'Undo clears cannot satisfy milestones');
profile.award({...clear,level:5});assert.equal(profile.status().rank.name,'Alchemist');
profile.award({...clear,level:11});assert.equal(profile.status().rank.name,'Wizard');
profile.award({...clear,level:16});assert.equal(profile.status().rank.name,'Archwizard');
for(let level=17;level<=25;level++)profile.award({...clear,level});
assert.equal(profile.status().rank.name,'Grand Archwizard');assert.equal(profile.status().progress,1);
const snapshot=JSON.stringify(profile.status());M.message(false,profile.status().rank.name);assert.equal(JSON.stringify(profile.status()),snapshot,'Fail messages must not deduct mastery');
const daily=M.create();const day={...clear,daily:true,day:'2026-10-18'};assert(daily.award(day).earned>0);assert.equal(daily.award(day).earned,0);assert(daily.award({...day,day:'2026-10-19'}).earned>0);assert.equal(daily.status().persisted,false);
const bad=M.create({getItem:()=>'{bad',setItem:()=>{throw Error('Denied');}});assert.doesNotThrow(()=>bad.award(clear));assert.equal(bad.status().persisted,false);
assert.equal(M.create({getItem:()=>JSON.stringify({version:1,records:{'journey:1':{xp:-50,cleanLevel:Infinity}}})}).status().xp,0);
// Exercise the actual game result path with its scoring and undo flag.
const c=clientHarness();c.reports=[];c.PotionTitles={finish:(won,run)=>c.reports.push({won,run})};
vm.runInContext('ranked=false;showEnd(true);',c);
assert.equal(c.reports[0].won,true);assert.equal(c.reports[0].run.rescued,true);assert.equal(c.reports[0].run.medal,1);
assert.equal(c.reports[0].run.day,new Date().toISOString().slice(0,10));
vm.runInContext('showEnd(false);',c);assert.equal(c.reports[1].won,false);
console.log('PASS: rank milestones, replay protection, improved combos, daily rollover, undo limits, persistence, storage failure, win/fail integration.');
